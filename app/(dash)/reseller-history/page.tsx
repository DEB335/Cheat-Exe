"use client";

import { useMemo, useState } from "react";

import { KeyHistoryPanel } from "@/components/key-history/KeyHistoryPanel";
import { ConfirmDialog } from "@/components/ui/ConfirmDialog";
import { useToast } from "@/components/ui/Toast";
import { del } from "@/lib/client-api";
import { useDashboard } from "@/lib/store";

export default function ResellerHistoryPage() {
  const toast = useToast();
  const refresh = useDashboard((s) => s.refresh);
  const isOwner = useDashboard((s) => s.user?.role === "OWNER");
  const [showConfirm, setShowConfirm] = useState(false);
  const [clearing, setClearing] = useState(false);

  // Same as the owner history: derive from a stable slice, never from a
  // selector that allocates.
  const keyHistory = useDashboard((s) => s.db.cheatExeKeyHistory);
  const history = useMemo(() => keyHistory.filter((k) => k.creator !== "admin"), [keyHistory]);

  const handleClear = async () => {
    setClearing(true);
    try {
      await del("/api/history?scope=reseller");
      await refresh();
      toast("Key history cleared successfully.", "success");
      setShowConfirm(false);
    } catch (err) {
      toast((err as Error).message, "error");
    } finally {
      setClearing(false);
    }
  };

  return (
    <>
      <ConfirmDialog
        open={showConfirm}
        onClose={() => setShowConfirm(false)}
        onConfirm={handleClear}
        title="Clear Reseller Key History"
        description="Are you sure you want to permanently clear all Reseller key history? This cannot be undone."
        confirmText="Clear History"
        confirmVariant="danger"
        loading={clearing}
      />

      <KeyHistoryPanel
        title={isOwner ? "Reseller Key History" : "My Key History"}
        subtitle="Keys generated by resellers."
        records={history}
        emptyText="No Reseller keys generated yet."
        showCreator
        onRefresh={async () => {
          await refresh();
          toast("Key history refreshed.", "success");
        }}
        // Only the owner may clear; a reseller never sees the button.
        onClear={isOwner ? () => setShowConfirm(true) : undefined}
      />
    </>
  );
}
