"use client";

import { useMemo } from "react";

import { KeyHistoryPanel } from "@/components/key-history/KeyHistoryPanel";
import { useToast } from "@/components/ui/Toast";
import { del } from "@/lib/client-api";
import { useDashboard } from "@/lib/store";

export default function OwnerHistoryPage() {
  const toast = useToast();
  const refresh = useDashboard((s) => s.refresh);
  // Select the stable slice and derive here: a selector that returns a
  // fresh array each call breaks useSyncExternalStore in Zustand v5.
  const keyHistory = useDashboard((s) => s.db.cheatExeKeyHistory);
  const history = useMemo(() => keyHistory.filter((k) => k.creator === "admin"), [keyHistory]);

  const clear = async () => {
    if (!confirm("Are you sure you want to permanently clear all Owner key history?")) return;
    try {
      await del("/api/history?scope=owner");
      await refresh();
      toast("Owner key history cleared successfully.", "success");
    } catch (err) {
      toast((err as Error).message, "error");
    }
  };

  return (
    <KeyHistoryPanel
      title="Owner Key History"
      subtitle="Keys generated by the Owner."
      records={history}
      emptyText="No Owner keys generated yet."
      showCopy
      onRefresh={async () => {
        await refresh();
        toast("Owner key history refreshed.", "success");
      }}
      onClear={clear}
    />
  );
}
