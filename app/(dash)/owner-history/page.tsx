"use client";

import { useMemo, useState } from "react";

import { KeyHistoryPanel } from "@/components/key-history/KeyHistoryPanel";
import { ConfirmDialog } from "@/components/ui/ConfirmDialog";
import { useToast } from "@/components/ui/Toast";
import { del } from "@/lib/client-api";
import { applyKeyHistoryClear } from "@/lib/optimistic";
import { useDashboard } from "@/lib/store";

export default function OwnerHistoryPage() {
  const toast = useToast();
  const refresh = useDashboard((s) => s.refresh);
  const patchDb = useDashboard((s) => s.patch);
  const restore = useDashboard((s) => s.restore);
  const user = useDashboard((s) => s.user);
  const [showConfirm, setShowConfirm] = useState(false);
  const [clearing, setClearing] = useState(false);

  // Select the stable slice and derive here: a selector that returns a
  // fresh array each call breaks useSyncExternalStore in Zustand v5.
  const keyHistory = useDashboard((s) => s.db.cheatExeKeyHistory);
  const history = useMemo(
    () =>
      keyHistory.filter((k) => {
        if (k.package === "EMULATOR BYPASS") return false;
        const c = (k.creator || "").trim().toLowerCase();
        return c === "admin" || c === "owner" || c.startsWith("owner (") || c.startsWith("owner ");
      }),
    [keyHistory],
  );

  const handleClear = async () => {
    setClearing(true);
    // Paint the empty list at once; the route clears the same rows for real
    // behind it, and the license API is left untouched.
    const snapshot =
      user && user.role === "OWNER"
        ? patchDb((db) =>
            applyKeyHistoryClear(db, "owner", { role: user.role, username: user.username }),
          )
        : null;
    setShowConfirm(false);
    try {
      await del("/api/history?scope=owner");
      toast("Owner key history cleared.", "success");
      await refresh();
    } catch (err) {
      if (snapshot) restore(snapshot);
      toast((err as Error).message, "error");
    } finally {
      setClearing(false);
    }
  };

  return (
    <>
      <ConfirmDialog
        open={showConfirm}
        onClose={() => setShowConfirm(false)}
        onConfirm={handleClear}
        title="Clear Owner Key History"
        description="This removes every Owner key from the panel's list — here and on every other page. The keys themselves stay active on the license API. This cannot be undone."
        confirmText="Clear History"
        confirmVariant="danger"
        loading={clearing}
      />

      <KeyHistoryPanel
        title="Owner Key History"
        subtitle="Keys generated by the Owner."
        records={history}
        emptyText="No Owner keys generated yet."
        showCopy
        onRefresh={async () => {
          await refresh();
          toast("Owner key history refreshed.", "success");
        }}
        onClear={() => setShowConfirm(true)}
      />
    </>
  );
}
